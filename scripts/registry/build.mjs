// Builds the HPC registry: registry/*.json from pinned upstream sources, then registry/SOURCES.md and registry/NOTICE.
//
//   scripts/dev.sh node scripts/registry/build.mjs [--refresh | --frozen] [lapack scalapack mpi …]
//
// Every download is checked against scripts/registry/sources.lock.json. A URL without a pin is pinned (and listed);
// changed content fails unless --refresh; --frozen (for CI) also refuses URLs without a pin. A full build drops pins
// that no builder used. Downloads are cached in .cache/registry/ (gitignored).
import { readFile, readdir, stat, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { gzipSync } from 'node:zlib';
import * as intrinsics from './intrinsics.mjs';
import * as lapack from './lapack.mjs';
import { FROZEN, isMain, loadSources, lockNotes, OUT_DIR, REFRESH, ROOT, saveLock } from './lib.mjs';
import * as mpi from './mpi.mjs';
import * as openacc from './openacc.mjs';
import * as openmp from './openmp.mjs';
import * as scalapack from './scalapack.mjs';
import * as vendors from './vendors.mjs';

/** In build order: vendors reads lapack.json. */
export const BUILDERS = { lapack, scalapack, mpi, openmp, openacc, intrinsics, vendors };

const LOCK_FILE = path.join(ROOT, 'scripts/registry/sources.lock.json');

/** registry/SOURCES.md: every pinned source with its version, licence, URLs and what the registry takes from it. */
async function sourcesMd(sources, results) {
  const lock = JSON.parse(await readFile(LOCK_FILE, 'utf8')).files;
  const lines = [
    '# Sources of the HPC registry',
    '',
    'The files in this folder are generated by `scripts/registry/*.mjs` from the pinned upstream sources below; do not',
    'edit them by hand. To rebuild them in Docker (the host needs no Node):',
    '',
    '```sh',
    'FDF_NODE_IMAGE=node:26-bookworm-slim scripts/dev.sh node scripts/registry/build.mjs',
    '```',
    '',
    '`scripts/registry/sources.json` describes the sources, and `scripts/registry/sources.lock.json` pins the SHA-256 of',
    'every download, so a build either reproduces these files or stops at the first source that changed. `--refresh`',
    'accepts changed sources after review; `--frozen` (for CI) also refuses downloads without a pin. Downloads are cached',
    'in `.cache/registry/`, each in a folder of its own, and are only ever parsed.',
    '',
    'The registry is used at build time only: pages embed just the entries they reference.',
    '',
    '## Files',
    '',
    '| File | Entries | Bytes | Contents |',
    '|---|---:|---:|---|',
  ];
  for (const r of results) lines.push(`| \`${r.file}\` | ${r.entries.toLocaleString('en-GB')} | ${r.bytes.toLocaleString('en-GB')} | ${r.about} |`);
  lines.push('', 'Each file starts with a `legend` that explains its fields, codes and tags, and a `links` section with the URL', 'rules of its link providers. `read.mjs` expands entries and builds their links.', '');
  lines.push('## Pinned sources', '');
  for (const s of sources.sources) {
    lines.push(`### ${s.name}`, '');
    lines.push(`- **Version:** ${s.version}`);
    lines.push(`- **Licence:** ${s.licence}`);
    lines.push(`- **Homepage:** <${s.homepage}>`);
    const pinned = Object.entries(lock).filter(([url]) => Object.values(s.urls).some((u) => urlMatches(u, url)));
    for (const [key, u] of Object.entries(s.urls)) {
      const hits = pinned.filter(([url]) => urlMatches(u, url));
      if (hits.length === 1 && hits[0][0] === u) lines.push(`- **${key}:** <${u}> (sha256 \`${hits[0][1].slice(0, 16)}…\`)`);
      else if (hits.length) lines.push(`- **${key}:** \`${u}\` (${hits.length} files, each pinned in sources.lock.json)`);
      else lines.push(`- **${key}:** \`${u}\``);
    }
    lines.push(`- **Used for:** ${s.uses}`);
    lines.push(`- **Copied:** ${s.copied}`, '');
  }
  lines.push('## Link targets', '', 'These sites are linked to; nothing is downloaded from them or copied.', '');
  for (const l of sources.links) lines.push(`- [${l.name}](${l.url}): ${l.note}`);
  lines.push('', '## Text not copied', '');
  lines.push(
    'No prose is taken from the GFDL manuals (gfortran, libgomp), the OpenMP, OpenACC or MPI specifications, Intel,',
    'NVIDIA or FFTW. From the specifications and manuals the registry keeps names, page numbers and fragment IDs only,',
    'and from the OpenACC specification whether each routine is a subroutine or a function. Its OpenMP (kinds',
    'included), OpenACC, BLACS, MPI-callback, MPI-type and vendor one-liners are our own, as are those of the',
    'ScaLAPACK C routines whose sources have no prose (?lamov, reshape, sl_gridreshape); the summaries of LAPACK,',
    'ScaLAPACK, Open MPI and M_intrinsics come from those projects under their permissive licences (see NOTICE).',
    '',
    '## Summaries',
    '',
    'A summary is its source\'s one-liner or first sentence: LAPACK\'s `\\brief` (else the first sentence of its',
    'Purpose), the first sentence of ScaLAPACK\'s Purpose, the summary line of an Open MPI man page, the NAME line of',
    'M_intrinsics. It is kept whole up to 200 characters (code points), what a hover card shows, and cut at a word,',
    'with an ellipsis, beyond that. Open MPI\'s RST markup is taken off, its substitutions (`|mdash|`,',
    '`|deprecated_favor|`) are expanded and its escapes undone; the words that LAPACK\'s and ScaLAPACK\'s prose',
    'breaks at the end of a line are joined. These slips of the sources are corrected (the `CORRECTIONS` tables of',
    '`scripts/registry/lapack.mjs`, `scalapack.mjs` and `mpi.mjs`):',
    '',
  );
  const tables = [
    ['Reference-LAPACK', lapack.CORRECTIONS],
    ['Reference-ScaLAPACK', scalapack.CORRECTIONS],
    ['Open MPI', mpi.CORRECTIONS],
  ];
  for (const [label, table] of tables) {
    for (const [name, fixes] of Object.entries(table)) {
      lines.push(`- \`${name}\` (${label}): ${fixes.map(([from, to]) => `\`${from}\` → \`${to}\``).join('; ')}`);
    }
  }
  lines.push('');
  return lines.join('\n');
}

function urlMatches(template, url) {
  if (!template.includes('{')) return template === url;
  const re = new RegExp(`^${template.replace(/[.*+?^$()|[\]\\]/g, '\\$&').replace(/\\?\{[^}]+\\?\}/g, '[^/]+')}$`);
  return re.test(url);
}

/** registry/NOTICE: the copyright notices and licence texts the permissive sources ask to be kept. */
function notice(sources, texts) {
  const block = (title, body) => [`${'='.repeat(78)}`, title, `${'='.repeat(78)}`, '', body.trim(), ''].join('\n');
  const parts = [
    [
      'fumadocs-fortran HPC registry (registry/*.json)',
      '',
      'Copyright (c) 2026 Neven Golenić. The registry\'s own data (one-liners, classifications, link rules) is MIT-licensed',
      'with the rest of fumadocs-fortran (see LICENSE). It also contains material from the works below, used under their',
      'licences, whose notices follow. SOURCES.md lists every source with its version and URL.',
      '',
      'Names, page numbers and fragment IDs are also taken from the OpenMP API Specification (© OpenMP Architecture',
      'Review Board), the MPI Standard (© University of Tennessee), the OpenACC Specification (© OpenACC-Standard.org) and',
      'the GCC gfortran manual (GFDL); none of their text is reproduced.',
      '',
    ].join('\n'),
  ];
  const named = {
    lapack: 'Reference-LAPACK 3.12.1 (BLAS and LAPACK): routine names, arguments, summaries and family titles',
    scalapack: 'Reference-ScaLAPACK 2.2.2: routine names, arguments and summaries',
    openmpi:
      'Open MPI: man-page summaries, the API catalogue (procedures, categories, mpi_f08 arguments) and the mpi_f08 ' +
      'types (components, null handles)',
    'mpi-abi-stubs': 'MPI ABI stubs: procedure, callback, handle-type and null-handle names',
    'llvm-openmp':
      'LLVM OpenMP runtime (omp_lib): routine interfaces, kinds and constants (Apache-2.0 WITH LLVM-exception)',
    'm-intrinsics': 'M_intrinsics: intrinsic categories, one-liners and arguments',
    'fortran-lang': 'fortran-lang.org: intrinsic page paths',
  };
  for (const [id, title] of Object.entries(named)) {
    if (!texts[id]) throw new Error(`NOTICE: no licence text for ${id}`);
    parts.push(block(title, texts[id]));
  }
  void sources;
  return parts.join('\n');
}

export async function buildAll(only = []) {
  const sources = await loadSources();
  const wanted = Object.keys(BUILDERS).filter((k) => !only.length || only.includes(k));
  const results = {};
  for (const name of wanted) {
    process.stderr.write(`building ${name}… `);
    results[name] = await BUILDERS[name].build();
    process.stderr.write(`${results[name].bytes.toLocaleString('en-GB')} bytes\n`);
  }
  const full = wanted.length === Object.keys(BUILDERS).length;
  await saveLock({ prune: full });

  if (full) {
    // the licence texts come from the pinned sources themselves
    const texts = {
      lapack: results.lapack.licence,
      scalapack: results.scalapack.licence,
      openmpi: results.mpi.licences.openmpi,
      'mpi-abi-stubs': results.mpi.licences['mpi-abi-stubs'],
      'llvm-openmp': results.openmp.licence.split(/\n=+\nSoftware from third parties/)[0].split(/\n=+\nLegacy LLVM License/)[0],
      'm-intrinsics': results.intrinsics.licences['m-intrinsics'],
      'fortran-lang': results.intrinsics.licences['fortran-lang'],
    };
    await writeFile(path.join(OUT_DIR, 'NOTICE'), notice(sources, texts));
    const about = {
      'lapack.json': 'BLAS and LAPACK 3.12.1: routines and precision families',
      'scalapack.json': 'ScaLAPACK 2.2.2 with TOOLS, PBLAS, REDIST and BLACS',
      'mpi.json': 'MPI 5.0 procedures callable from Fortran (4.1 alias), callbacks, the derived types of mpi_f08',
      'openmp.json': 'OpenMP 6.1, 6.0 and 5.2: directives, clauses, routines, environment variables, kinds, constants',
      'openacc.json': 'OpenACC 3.4: directives, clauses, routines, environment variables',
      'intrinsics.json': 'Fortran intrinsic procedures',
      'vendors.json': 'oneMKL (lapack95, blas95), OpenBLAS and cuBLAS',
    };
    const rows = Object.values(results).map((r) => ({ file: r.file, bytes: r.bytes, entries: r.stats.entries ?? r.stats.routines, about: about[r.file] }));
    await writeFile(path.join(OUT_DIR, 'SOURCES.md'), await sourcesMd(sources, rows));
  }
  return { results, full };
}

/** Sizes of the registry folder: raw and gzipped, per file. */
export async function sizes() {
  const out = [];
  for (const f of (await readdir(OUT_DIR)).sort()) {
    const p = path.join(OUT_DIR, f);
    if (!(await stat(p)).isFile()) continue;
    const buf = await readFile(p);
    out.push({ file: f, bytes: buf.length, gzip: gzipSync(buf, { level: 9 }).length });
  }
  return out;
}

if (isMain(import.meta.url)) {
  const only = process.argv.slice(2).filter((a) => !a.startsWith('--'));
  const { results } = await buildAll(only);
  for (const n of lockNotes) console.log(n);
  console.log(`\n${REFRESH ? 'refresh' : FROZEN ? 'frozen' : 'pinned'} build`);
  for (const [name, r] of Object.entries(results)) {
    const { problems = [], ...rest } = r.stats;
    console.log(`${name}: ${JSON.stringify(Object.fromEntries(Object.entries(rest).filter(([, v]) => typeof v === 'number')))}`);
    for (const p of problems) console.log(`  ! ${p}`);
  }
  const all = await sizes();
  for (const s of all) console.log(`${s.file.padEnd(16)} ${String(s.bytes).padStart(9)} ${String(s.gzip).padStart(8)}`);
  const total = all.reduce((a, s) => [a[0] + s.bytes, a[1] + s.gzip], [0, 0]);
  console.log(`${'total'.padEnd(16)} ${String(total[0]).padStart(9)} ${String(total[1]).padStart(8)}`);
}
