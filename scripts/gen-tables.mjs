// Writes the two data tables the page emitter needs, which keeps it free of dependencies:
//   src/emit/shiki-langs.js  the languages Shiki bundles (ids and aliases), so that a code block in a doc comment
//                            never names one that a fumadocs site cannot highlight (its build would fail);
//   src/emit/entities.js     the HTML 4 named character references (and &apos;), which plain-text summaries decode.
// Run it in Docker with the docs site's node_modules, from the repository root:
//   docker run --rm -u "$(id -u):$(id -g)" -v fdf-docs-node-modules:/site/node_modules:ro -v "$PWD":/site/repo \
//     -w /site/repo node:24-bookworm node scripts/gen-tables.mjs
import fs from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(process.env.SITE_MODULES ?? '/site/node_modules/');
const { bundledLanguagesInfo } = await import(require.resolve('shiki'));
const { characterEntitiesHtml4 } = await import(require.resolve('character-entities-html4'));
const shikiVersion = require('shiki/package.json').version;

const langs = new Set();
for (const l of bundledLanguagesInfo) {
  langs.add(l.id.toLowerCase());
  for (const a of l.aliases ?? []) langs.add(a.toLowerCase());
}
const sorted = [...langs].sort();
const lines = [];
for (let i = 0, line = ' '; i < sorted.length; i++) {
  const item = ` '${sorted[i]}',`;
  if (line.length + item.length > 118) { lines.push(line); line = ' '; }
  line += item;
  if (i === sorted.length - 1) lines.push(line);
}
fs.writeFileSync('src/emit/shiki-langs.js', `// Generated by scripts/gen-tables.mjs from Shiki ${shikiVersion}. Do not edit.
// The languages Shiki bundles, ids and aliases, in lower case.
export const SHIKI_LANGS = new Set([
${lines.join('\n')}
]);
`);

const entities = { ...characterEntitiesHtml4, apos: "'" };
const pairs = Object.entries(entities).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const elines = [];
for (let i = 0, line = ' '; i < pairs.length; i++) {
  const [k, v] = pairs[i];
  const item = ` ${k}: ${JSON.stringify(v).replace(/[\u007f-\uffff]/g, (c) => `\\u${c.charCodeAt(0).toString(16).padStart(4, '0')}`)},`;
  if (line.length + item.length > 118) { elines.push(line); line = ' '; }
  line += item;
  if (i === pairs.length - 1) elines.push(line);
}
fs.writeFileSync('src/emit/entities.js', `// Generated by scripts/gen-tables.mjs from character-entities-html4. Do not edit.
// The HTML 4 named character references, and &apos;.
export const ENTITIES = Object.freeze({
${elines.join('\n')}
});
`);
console.log(`${sorted.length} Shiki languages, ${pairs.length} entities`);
