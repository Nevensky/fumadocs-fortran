// Generates the examples of the Doc comments page (content/docs/reference/doc-comments.mdx). Each Fortran file in
// snippets/doc-comments goes through generate(), and a partial beside it, <name>.mdx, which the page includes, shows
// the file and the entries generate writes for it: in a Preview tab as a page shows them, and in an MDX tab as
// written. Both leave out each entry's heading and source block. In the Preview, a link to another entry of the same
// file leads to that entry on the page. Other files in the folder, such as a Markdown file that a FORD {!file!}
// include reads, are read from there, since the folder is the project root of every run.
//
//   node docs/scripts/gen-examples.mjs           writes the partials, and deletes those whose Fortran file is gone
//   node docs/scripts/gen-examples.mjs --check   writes nothing, and exits 1 when a partial is missing, differs from
//                                                what generate writes now, or has no Fortran file (the prebuild)
//
// Runs without the site's node_modules, as gen-showcase.mjs does (in scripts/dev.sh on a machine without Node).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { EXTENSIONS, generate } from '../../src/index.js';

const repo = fileURLToPath(new URL('../../', import.meta.url));
const folder = 'docs/snippets/doc-comments';
const dir = path.join(repo, folder);
const check = process.argv.includes('--check');
const unknown = process.argv.slice(2).filter((a) => a !== '--check');
if (unknown.length) fail(`unknown argument ${unknown[0]}; the only option is --check`);

// the URL generate gives the pages by default, which the MDX tab shows
const BASE = '/docs/api';
const GENERATED = '{/* Generated by docs/scripts/gen-examples.mjs from ';

function fail(message) {
  process.stderr.write(`gen-examples: ${message}\n`);
  process.exit(2);
}

/** `1 diagnostic`, `2 diagnostics`: a count and its noun. */
const count = (n, noun) => `${n} ${noun}${n === 1 ? '' : 's'}`;

/** A fence longer than any run of backticks in the text. */
function fence(text) {
  let f = '```';
  while (text.includes(f)) f += '`';
  return f;
}

/**
 * The entries of a generated page, in page order: the text under each ### heading up to the next heading, without
 * its source block, and the anchor the heading gives it. The unit's own part (badges, its source) and the section
 * headings are left out.
 */
function entriesOf(mdx, page) {
  const body = mdx.replace(/^---\n[\s\S]*?\n---\n/, '');
  const entries = [];
  let cur = null;
  let close = null; // the closing line of the code block the line is in
  for (const line of body.split('\n')) {
    if (close) {
      if (close.test(line)) close = null;
    } else if (/^ *(`{3,}|~{3,})/.test(line)) {
      const marks = /^ *(`{3,}|~{3,})/.exec(line)[1];
      close = new RegExp(`^ *\\${marks[0]}{${marks.length},} *$`);
    } else {
      const h = /^### .* \[#([^\]]+)\]$/.exec(line);
      if (h) {
        cur = { anchor: h[1], lines: [] };
        entries.push(cur);
        continue;
      }
      if (/^#{1,2} /.test(line)) {
        cur = null;
        continue;
      }
      if (/^#{4,6} /.test(line)) throw new Error(`${page}: a heading inside an entry: ${line}`);
    }
    if (cur) cur.lines.push(line);
  }
  for (const e of entries) {
    let text = e.lines.join('\n');
    // the source block: a header alone (source: 'link'), or a block that opens to the code
    text = text.replace(/^<FortranSource\b[^\n]*\/>$/gm, '')
      .replace(/^<FortranSource\b[^\n]*>\n[\s\S]*?\n<\/FortranSource>$/gm, '');
    if (/<FortranSource\b/.test(text)) throw new Error(`${page}: a source block that was not taken out`);
    e.text = text.replace(/\n{3,}/g, '\n\n').trim();
  }
  return entries;
}

/** The partial of one Fortran file. */
async function partialOf(file) {
  const name = file.replace(/\.[^.]+$/, '');
  const out = fs.mkdtempSync(path.join(os.tmpdir(), 'fdf-examples-'));
  let r;
  try {
    r = await generate({ root: dir, sources: [file], out, graphs: false, source: 'link' });
  } finally {
    fs.rmSync(out, { recursive: true, force: true });
  }
  if (r.ir.diagnostics.length) {
    const d = r.ir.diagnostics[0];
    throw new Error(`${file}: ${count(r.ir.diagnostics.length, 'diagnostic')}, the first ${d.file}:${d.line}: ${d.message}`);
  }
  // a unit's own doc goes into its page's description and the part above its entries, which are not shown
  for (const e of Object.values(r.ir.entities)) {
    if (!e.parent && e.kind !== 'procedure' && e.doc?.blocks?.length) {
      throw new Error(`${file}: the doc of ${e.kind} ${e.name} would not be shown: document its entities instead`);
    }
  }
  const pages = r.pages.filter((p) => p.path !== 'index.mdx');
  const entries = pages.flatMap((p) => entriesOf(p.mdx, `${file}, ${p.path}`).map((e) => ({ ...e, url: p.url })));
  if (!entries.length) throw new Error(`${file}: generate wrote no entry`);
  // the Preview's links: an entry's URL becomes the id of that entry on the Doc comments page
  const ids = new Map();
  for (const e of entries) {
    const id = `ex-${name}-${e.anchor}`;
    if ([...ids.values()].includes(id)) throw new Error(`${file}: two entries with the anchor ${e.anchor}`);
    ids.set(`${e.url}#${e.anchor}`, id);
  }
  const linked = new Set();
  const link = (url) => {
    const id = ids.get(url);
    if (!id) throw new Error(`${file}: a link to ${url}, which is not an entry of this file`);
    linked.add(id);
    return `#${id}`;
  };
  // in a Markdown link, a JSX href (FortranRef) or the JSON of a row's refs
  const target = new RegExp(`(\\]\\(|href="|"href":")(${BASE}(?:/[^\\s")]*)?)(?=[)"])`, 'g');
  const preview = entries.map((e) => e.text.replace(target, (m, lead, url) => lead + link(url)));
  // a link's target, before the entry: scroll-m-28 is the margin Fumadocs gives a heading, so that the entry stops
  // below the page's sticky bars as a heading does
  const shown = entries.map((e, i) => {
    const id = ids.get(`${e.url}#${e.anchor}`);
    return linked.has(id) ? `<div id="${id}" className="scroll-m-28" />\n\n${preview[i]}` : preview[i];
  }).join('\n\n');
  const mdx = entries.map((e) => e.text).join('\n\n');
  const source = fs.readFileSync(path.join(dir, file), 'utf8').replace(/\s+$/, '');
  const form = r.ir.files.find((f) => f.path === file)?.form;
  const fs1 = fence(source);
  const fs2 = fence(mdx);
  return `${GENERATED}${folder}/${file}. Do not edit. */}

${fs1}${form === 'fixed' ? 'f77' : 'f90'} title="${file}"
${source}
${fs1}

<Tabs items={['Preview', 'MDX']}>
<Tab value="Preview">

${shown}

</Tab>
<Tab value="MDX">

${fs2}mdx
${mdx}
${fs2}

</Tab>
</Tabs>
`;
}

const exts = new Set(EXTENSIONS);
let names;
try {
  names = fs.readdirSync(dir).sort();
} catch (e) {
  fail(`cannot read ${folder}: ${e.message}`);
}
const sources = names.filter((n) => exts.has(path.extname(n).slice(1)));
const want = new Map();
for (const file of sources) {
  const partial = `${file.replace(/\.[^.]+$/, '')}.mdx`;
  if (want.has(partial)) fail(`${folder}: two Fortran files give ${partial}`);
  try {
    want.set(partial, await partialOf(file));
  } catch (e) {
    fail(e.message);
  }
}
// a partial this script wrote whose Fortran file is gone
const stale = names.filter((n) => n.endsWith('.mdx') && !want.has(n)
  && fs.readFileSync(path.join(dir, n), 'utf8').startsWith(GENERATED));

const drift = [];
for (const [partial, text] of want) {
  let old = null;
  try {
    old = fs.readFileSync(path.join(dir, partial), 'utf8');
  } catch {
    // not written yet
  }
  if (old === text) continue;
  drift.push(`${partial} ${old === null ? 'is missing' : 'differs from what generate writes'}`);
  if (!check) fs.writeFileSync(path.join(dir, partial), text);
}
for (const n of stale) {
  drift.push(`${n} has no Fortran file`);
  if (!check) fs.unlinkSync(path.join(dir, n));
}

if (check) {
  if (drift.length) {
    process.stderr.write(`gen-examples: the Doc comments examples in ${folder} are out of date:\n`);
    for (const d of drift) process.stderr.write(`  ${d}\n`);
    process.stderr.write('write them again from the repository root, with node docs/scripts/gen-examples.mjs (or '
      + 'scripts/dev.sh node docs/scripts/gen-examples.mjs), and commit them\n');
    process.exit(1);
  }
  console.log(`gen-examples: ${count(want.size, 'example')}, up to date`);
} else {
  console.log(`gen-examples: ${count(want.size, 'example')} (${drift.length} changed or removed)`);
}
