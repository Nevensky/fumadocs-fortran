// Generates the Showcase from examples/modern: the API reference in content/docs/showcase/modern, and a page with the
// example sources themselves (content/docs/showcase/sources.mdx), so that input and output can be compared.
// Runs without the site's node_modules: node docs/scripts/gen-showcase.mjs (in scripts/dev.sh on a machine without Node).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { generate } from '../../src/index.js';

const root = fileURLToPath(new URL('../../', import.meta.url));
const r = await generate({
  root,
  sources: ['examples/modern/src'],
  // the HPC guards examples/modern uses; init writes the ones a project uses into its config
  cpp: { macros: { _OPENMP: 1, USE_MPI: 1 } },
  out: 'docs/content/docs/showcase/modern',
  baseUrl: '/docs/showcase/modern',
  title: 'examples/modern',
  description: 'The API reference fumadocs-fortran generates for examples/modern: a FORD-documented module with OpenMP, OpenACC, MPI and coarrays, a Doxygen-documented module, and a LAPACK-style fixed-form routine.',
  display: ['public', 'protected', 'private'],
  repo: { url: 'https://github.com/Nevensky/fumadocs-fortran', rev: 'main' },
  defaultOpen: true,
});
console.log(`showcase: ${r.written.length} files (${r.changed.length} changed, ${r.removed.length} removed), ${r.ir.diagnostics.length} diagnostics`);
for (const d of r.ir.diagnostics) console.log(`  ${d.file}:${d.line}: ${d.message}`);

// the sources page: every example file in a code block, free form as f90 and fixed form as f77
const files = r.ir.files.filter((f) => !f.skipped);
const fence = (code) => {
  let f = '```';
  while (code.includes(f)) f += '`';
  return f;
};
const sections = files.map((f) => {
  const text = fs.readFileSync(path.join(root, f.path), 'utf8').replace(/\s+$/, '');
  const fc = fence(text);
  const lang = f.form === 'fixed' ? 'f77' : 'f90';
  const how = f.form === 'fixed' ? 'fixed form' : 'free form';
  return `## ${path.basename(f.path)}\n\n\`${f.path}\`: ${f.lines} lines, ${how}${f.cpp ? ', with preprocessor directives' : ''}.\n\n${fc}${lang} title="${path.basename(f.path)}"\n${text}\n${fc}`;
});
const page = `---
title: "Example sources"
description: "The Fortran files the examples/modern reference is generated from."
---

{/* Generated by docs/scripts/gen-showcase.mjs from examples/modern/src. Do not edit. */}

These are the inputs: the reference under examples/modern is what \`fumadocs-fortran generate\` writes for them, with
\`_OPENMP\` and \`USE_MPI\` defined and private entities shown as well (\`--display public,protected,private\`; by
default it shows public and protected ones only). Compare a procedure here with its entry there.

${sections.join('\n\n')}
`;
const out = path.join(root, 'docs/content/docs/showcase/sources.mdx');
let old = null;
try {
  old = fs.readFileSync(out, 'utf8');
} catch {
  // first run
}
if (old !== page) fs.writeFileSync(out, page);
console.log(`sources page: ${files.length} files${old === page ? ', unchanged' : ''}`);
